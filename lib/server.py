# HTTP
# --------------------------------------------------------------------------

class Handler(BaseHTTPRequestHandler):
    server_version = "m720-config"
    token = ""

    def log_message(self, fmt, *args):
        pass  # keep the terminal clean

    # -- helpers ----------------------------------------------------------
    def _send(self, code, body, ctype="application/json"):
        if not isinstance(body, bytes):
            body = body.encode()
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.end_headers()
        self.wfile.write(body)

    def _json(self, code, obj):
        self._send(code, json.dumps(obj))

    def _authorised(self):
        if self.headers.get("X-Token") == self.token:
            return True
        return self.path.split("?token=")[-1].split("&")[0] == self.token

    def _body(self):
        length = int(self.headers.get("Content-Length") or 0)
        if length <= 0 or length > 512_000:
            return {}
        try:
            return json.loads(self.rfile.read(length) or b"{}")
        except ValueError:
            return {}

    # -- routes -----------------------------------------------------------
    def do_GET(self):
        route = self.path.split("?")[0]

        if route == "/":
            if not self._authorised():
                return self._send(403, "Bad or missing token. Re-run `mouse modify`.",
                                  "text/plain")
            try:
                html = UI_FILE.read_text()
            except OSError as exc:
                return self._send(500, f"cannot read ui.html: {exc}", "text/plain")
            html = html.replace("__TOKEN__", self.token)
            return self._send(200, html, "text/html; charset=utf-8")

        if not self._authorised():
            return self._json(403, {"error": "bad token"})

        if route == "/api/state":
            text, err = read_current_config()
            return self._json(200, {
                "buttons": BUTTONS,
                "current": parse_config(text),
                "raw": text or "",
                "readError": err,
                "profiles": load_profiles(),
                "service": service_status(),
                "scroll": imwheel_state(),
            })

        if route == "/api/status":
            return self._json(200, service_status())

        return self._json(404, {"error": "not found"})

    def do_POST(self):
        route = self.path.split("?")[0]
        if not self._authorised():
            return self._json(403, {"error": "bad token"})

        if route == "/api/preview":
            try:
                return self._json(200, {"config": generate_config(self._body())})
            except Exception as exc:
                return self._json(400, {"error": f"could not build config: {exc}"})

        if route == "/api/apply":
            body = self._body()
            try:
                text = generate_config(body)
            except Exception as exc:
                return self._json(400, {"error": f"could not build config: {exc}"})
            ok, message = apply_config(text)
            # Scroll speed is a separate, unprivileged mechanism (imwheel), so
            # apply it either way — a logid rollback does not invalidate it.
            sok, smsg = apply_scroll(body.get("settings"))
            return self._json(200 if ok else 500, {
                "ok": ok, "message": message, "config": text,
                "scrollOk": sok, "scrollMessage": smsg,
                "service": service_status(), "scroll": imwheel_state(),
            })

        if route == "/api/revert":
            ok, message = run_privileged(["--revert"])
            return self._json(200 if ok else 500, {
                "ok": ok, "message": message, "service": service_status(),
            })

        if route == "/api/profiles":
            body = self._body()
            if not isinstance(body.get("profiles"), dict):
                return self._json(400, {"error": "malformed profiles payload"})
            try:
                save_profiles({"active": body.get("active", "Default"),
                               "profiles": body["profiles"]})
            except OSError as exc:
                return self._json(500, {"error": str(exc)})
            return self._json(200, {"ok": True})

        if route == "/api/quit":
            threading.Timer(0.3, lambda: os._exit(0)).start()
            return self._json(200, {"ok": True})

        return self._json(404, {"error": "not found"})


def main():
    if not UI_FILE.exists():
        sys.exit(f"m720-config: {UI_FILE} is missing — reinstall m720-config")

    Handler.token = secrets.token_urlsafe(24)

    httpd = None
    for port in range(8770, 8800):
        try:
            httpd = ThreadingHTTPServer(("127.0.0.1", port), Handler)
            break
        except OSError:
            continue
    if httpd is None:
        sys.exit("m720-config: no free port in 8770-8799")

    url = f"http://127.0.0.1:{httpd.server_port}/?token={Handler.token}"
    print("M720 configuration UI")
    print(f"  {url}")
    print("Leave this running while you configure. Ctrl-C to stop.")

    if "--no-browser" not in sys.argv:
        threading.Timer(0.4, lambda: webbrowser.open(url)).start()

    try:
        httpd.serve_forever()
    except KeyboardInterrupt:
        print("\nstopped.")


if __name__ == "__main__":
    main()
