def service_status():
    def sh(args):
        try:
            return subprocess.run(args, capture_output=True, text=True,
                                  timeout=5).stdout.strip()
        except Exception:
            return ""

    active = sh(["systemctl", "is-active", SERVICE])
    enabled = sh(["systemctl", "is-enabled", SERVICE])
    since = sh(["systemctl", "show", SERVICE, "-p", "ActiveEnterTimestamp",
                "--value"])
    logs = sh(["journalctl", "-u", SERVICE, "-n", "25", "--no-pager", "-o",
               "short-iso"])

    connected = None
    for line in reversed(logs.splitlines()):
        if "Device found" in line:
            connected = True
            break
        if "disconnected" in line:
            connected = False
            break

    return {
        "active": active,
        "enabled": enabled,
        "since": since,
        "connected": connected,
        "logs": logs.splitlines()[-25:],
    }


def run_privileged(args):
    """Run mouse-apply as root, preferring a graphical prompt when we have one."""
    graphical = bool(os.environ.get("DISPLAY") or os.environ.get("WAYLAND_DISPLAY"))
    attempts = []
    if graphical and shutil.which("pkexec"):
        attempts.append(["pkexec", APPLY_HELPER, *args])
    attempts.append(["sudo", "-n", APPLY_HELPER, *args])

    last = None
    for cmd in attempts:
        try:
            r = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
        except FileNotFoundError:
            continue
        except subprocess.TimeoutExpired:
            return False, "timed out waiting for authentication"
        if r.returncode == 0:
            return True, (r.stdout or "").strip()
        last = (r.stderr or r.stdout or "").strip()
        # 126/127 from pkexec mean dismissed/not-authorised; try the next path.
        if cmd[0] == "pkexec" and r.returncode in (126, 127):
            continue
        return False, last
    return False, last or (
        "could not gain root. Run `sudo -v` in a terminal first, or install "
        "policykit-1 so the graphical prompt works."
    )


def apply_config(text):
    fd, path = tempfile.mkstemp(prefix="m720-", suffix=".cfg")
    try:
        with os.fdopen(fd, "w") as fh:
            fh.write(text)
        os.chmod(path, 0o644)   # pkexec drops to a clean env; keep it readable
        return run_privileged([path])
    finally:
        try:
            os.unlink(path)
        except OSError:
            pass


def load_profiles():
    try:
        data = json.loads(PROFILES_FILE.read_text())
        if isinstance(data, dict) and isinstance(data.get("profiles"), dict):
            return data
    except (OSError, ValueError):
        pass
    return {"active": "Default", "profiles": {}}


def save_profiles(data):
    CONFIG_HOME.mkdir(parents=True, exist_ok=True)
    tmp = PROFILES_FILE.with_suffix(".tmp")
    tmp.write_text(json.dumps(data, indent=2))
    tmp.replace(PROFILES_FILE)


